function inicializarUbigeo() {
    const selectDep = document.getElementById('f1Dep');
    if (!selectDep) return;

    selectDep.innerHTML = "";
    
    // Lista ordenada de departamentos
    const listaDepartamentos = Object.keys(ubigeoPeru).sort();

    // Ponemos primero Áncash por ser la región local
    const indiceAncash = listaDepartamentos.indexOf("Áncash");
    if (indiceAncash > -1) {
        listaDepartamentos.splice(indiceAncash, 1);
        listaDepartamentos.unshift("Áncash");
    }

    listaDepartamentos.forEach(dep => {
        const opt = document.createElement('option');
        opt.value = dep;
        opt.textContent = dep;
        if (dep === "Áncash") opt.selected = true;
        selectDep.appendChild(opt);
    });

    cargarProvincias();
}

function cargarProvincias() {
    const depSeleccionado = document.getElementById('f1Dep').value;
    const selectProv = document.getElementById('f1Prov');
    if (!selectProv) return;

    selectProv.innerHTML = "";
    const provincias = ubigeoPeru[depSeleccionado] ? Object.keys(ubigeoPeru[depSeleccionado]) : [];

    provincias.forEach(prov => {
        const opt = document.createElement('option');
        opt.value = prov;
        opt.textContent = prov;
        // Si estamos en Áncash, seleccionamos Carhuaz por defecto
        if (depSeleccionado === "Áncash" && prov === "Carhuaz") opt.selected = true;
        selectProv.appendChild(opt);
    });

    cargarDistritos();
}

function cargarDistritos() {
    const depSeleccionado = document.getElementById('f1Dep').value;
    const provSeleccionada = document.getElementById('f1Prov').value;
    const selectDist = document.getElementById('f1Dist');
    if (!selectDist) return;

    selectDist.innerHTML = "";
    const distritos = (ubigeoPeru[depSeleccionado] && ubigeoPeru[depSeleccionado][provSeleccionada]) 
        ? ubigeoPeru[depSeleccionado][provSeleccionada] 
        : ["Distrito Único / No especificado"];

    distritos.forEach(dist => {
        const opt = document.createElement('option');
        opt.value = dist;
        opt.textContent = dist;
        // Si estamos en Carhuaz, distrito Carhuaz por defecto
        if (provSeleccionada === "Carhuaz" && dist === "Carhuaz") opt.selected = true;
        selectDist.appendChild(opt);
    });
}